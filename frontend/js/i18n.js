function getCurrentLanguage() {
  const lang = localStorage.getItem("medidecode_lang") || "en";
  return TRANSLATIONS[lang] ? lang : "en";
}

function t(key, replacements = {}) {
  const lang = getCurrentLanguage();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = dict[key] || TRANSLATIONS.en[key] || key;

  Object.keys(replacements).forEach((placeholder) => {
    text = text.replace(new RegExp("%" + placeholder + "%", "g"), replacements[placeholder]);
  });

  return text;
}

function applyTranslations() {
  const lang = getCurrentLanguage();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) {
      el.setAttribute("placeholder", dict[key]);
    }
  });

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (dict[key]) {
      el.setAttribute("title", dict[key]);
    }
  });

  document.documentElement.lang = lang;
}

function setLanguage(lang) {
  const nextLang = TRANSLATIONS[lang] ? lang : "en";
  localStorage.setItem("medidecode_lang", nextLang);
  applyTranslations();

  if (typeof renderSidebar === "function") {
    const sidebar = document.getElementById("app-sidebar");
    if (sidebar) {
      renderSidebar(sidebar.dataset.active);
    }
  }

  if (typeof renderTopbar === "function") {
    renderTopbar();
  }

  document.dispatchEvent(new CustomEvent("languageChanged", { detail: { language: nextLang } }));
}

function getLanguageName(lang) {
  const names = { en: "English", te: "తెలుగు", hi: "हिन्दी" };
  return names[lang] || names.en;
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  if (typeof renderSidebar === "function") {
    const sidebar = document.getElementById("app-sidebar");
    if (sidebar) {
      renderSidebar(sidebar.dataset.active);
    }
  }
  if (typeof renderTopbar === "function") {
    renderTopbar();
  }
});